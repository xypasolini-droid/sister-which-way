function chooseWithHistory(state: BranchState, choiceId: string, replayLegacy = false): { state: BranchState; consequence: string; changes: string[] } | null {
  if (state.endingId || state.history.length >= 35) return null;
  const choice = choicesFor(state, replayLegacy).find(item => item.id === choiceId);
  if (!choice?.enabled) return null;
  const effect = choice.effect ?? {};
  const next: BranchState = { ...state, stats: { ...state.stats }, flags: [...state.flags], history: [...state.history], nodeId: choice.next };
  const changes: string[] = [];
  for (const [key, amount] of Object.entries(effect.stats ?? {}) as [keyof Stats, number][]) {
    next.stats[key] = Math.max(0, Math.min(10, state.stats[key] + amount));
    const delta = next.stats[key] - state.stats[key];
    if (delta) changes.push(`${STAT_LABELS[key]} ${delta > 0 ? '+' : ''}${delta}`);
  }
  next.flags = [...new Set([...next.flags.filter(f => !(effect.remove ?? []).includes(f)), ...(effect.add ?? [])])];
  for (const key of ['outfit', 'scarf', 'sister', 'father'] as const) {
    if (effect[key] !== undefined) Object.assign(next, { [key]: effect[key] });
  }
  if (effect.outfit && effect.outfit !== state.outfit) changes.push(effect.outfit === 'worker' ? '换上长衫与宽裤' : effect.outfit === 'travel' ? '收拾远行衣物' : '换回日常衣着');
  if (effect.sister && effect.sister !== state.sister) changes.push(effect.sister === 'apart' ? '姐姐暂时离开身边' : effect.sister === 'injured' ? '姐姐受伤，需要照护' : '姐姐重新与你同行');
  if (effect.father && effect.father !== state.father) changes.push(effect.father === 'free' ? '父亲回到身边' : effect.father === 'missing' ? '父亲被带走' : '得知父亲去向');
  const consequence = consequenceFor(state, choice);
  next.history.push({ nodeId: state.nodeId, choiceId: choice.id, label: choice.label, consequence });
  if (next.storyRevision === 5 && next.nodeId === 'n30') {
    // The action already chosen is the ending. Never insert an eighth "next" click.
    next.endingId = getShortFate(next);
    if (next.endingId === 'lantern' && !next.flags.includes('guideGrown')) next.flags.push('guideGrown');
  } else if (choice.finish) next.endingId = endingFor(next, choice.finish);
  return { state: next, consequence, changes };
}

export function choose(state: BranchState, choiceId: string) { return chooseWithHistory(state, choiceId); }

export function getEnding(state: BranchState): Ending | null {
  if (state.storyRevision !== 5 && state.endingId) {
    const legacy = LEGACY_ENDINGS.find(item => item.id === state.endingId);
    if (!legacy) return null;
    const ending = projectLegacyEnding(state, legacy);
    return { ...ending, title: `旧版结局 · ${ending.title}`, summary: `这是此前已完成的旧版路线，保留当时实际发生的事。${ending.summary}`, unlockedBy: '旧版存档保留；重新开始可体验七次决定、五种独立命运的新故事。' };
  }
  const ending = ENDING_CONTENT.find(item => item.id === state.endingId);
  if (ending && state.storyRevision === 5 && state.storyContentRevision !== 6) return { ...projectEnding(state, ending), title: `旧版结局 · ${ending.title}`, summary: `这是此前完成的五结局路线，保留原有去向；未替你执行本次新增的行动。${ending.summary}`, unlockedBy: '旧版存档保留。重新开始可体验调整后的选择。' };
  return ending ? projectEnding(state, ending) : null;
}

/** Deliberately finite text interpreter: never invents an action that the scene cannot execute. */
export function interpretChoice(state: BranchState, text: string): { choiceId: string | null; message: string } {
  const input = text.trim();
  const choices = getChoices(state);
  if (!input) return { choiceId: null, message: '先写下你想做的事。' };
  if (input.length > 240) return { choiceId: null, message: '这一句请控制在 240 字以内。' };
  if (/[?？]|^(怎么办|怎么走|该怎么|能不能|可不可以|为什么)/.test(input)) return { choiceId: null, message: '这是一个问题，还没有替你作出决定。看看姐姐的话，或明确写下你准备做的事。' };
  const numeral = input.match(/^(?:选|选择|我选)?\s*([123一二三ABCabc])(?:[。.!！]?)$/);
  if (numeral) {
    const index = '123'.includes(numeral[1]) ? Number(numeral[1]) - 1 : '一二三'.includes(numeral[1]) ? '一二三'.indexOf(numeral[1]) : 'abc'.indexOf(numeral[1].toLowerCase());
    const choice = choices[index];
    return choice?.enabled ? { choiceId: choice.id, message: `准备选择：${choice.label}` } : { choiceId: null, message: choice?.reason || '这一页没有这个选项。' };
  }
  const direct = choices.find(c => input.replace(/[，。！？、\s]/g, '') === c.label.replace(/[，。！？、\s]/g, ''));
  if (direct) return direct.enabled ? { choiceId: direct.id, message: `准备选择：${direct.label}` } : { choiceId: null, message: direct.reason };
  // Ambiguous negations do not silently turn into the action being rejected.
  if (/(不要|不想|不能|别去|不去|不选|不愿|不再|如果|假如|也许|或者|要是)/.test(input)) return { choiceId: null, message: '这句话包含否定、条件或多个可能。请明确写下想采取的行动，或直接选择本页的一项行动。' };
  const ranked = choices.map(choice => ({ choice, score: choice.keywords.reduce((sum, keyword) => sum + (input.includes(keyword) ? Math.max(2, keyword.length) : 0), 0) })).sort((a, b) => b.score - a.score);
  if (!ranked[0] || ranked[0].score < 2 || ranked[0].score === ranked[1]?.score) return { choiceId: null, message: '这一页还没能确定你想走哪条路。可以写得更具体，或从本页的行动中选一项；世界暂时保持原样。' };
  const choice = ranked[0].choice;
  return choice.enabled ? { choiceId: choice.id, message: `这句话对应：${choice.label}` } : { choiceId: null, message: choice.reason };
}

/** Saves are replayed rather than trusted: copied counters cannot manufacture an ending. */
export function validateBranchState(raw: unknown): BranchState | null {
  if (!raw || typeof raw !== 'object') return null;
  const input = raw as Partial<BranchState>;
  if (input.version !== 3 || !Array.isArray(input.history) || input.history.length > 35 || typeof input.nodeId !== 'string') return null;
  if (input.edition !== undefined && input.edition !== 'short') return null;
  if (input.storyRevision !== undefined && (input.storyRevision !== 5 || input.edition !== 'short')) return null;
  if (input.storyContentRevision !== undefined && (input.storyContentRevision !== 6 || input.storyRevision !== 5)) return null;
  let replayed = createState(input.edition, input.storyRevision === 5);
  if (input.storyContentRevision !== 6) delete replayed.storyContentRevision;
  for (const entry of input.history) {
    if (!entry || typeof entry !== 'object' || entry.nodeId !== replayed.nodeId || typeof entry.choiceId !== 'string') return null;
    const result = chooseWithHistory(replayed, entry.choiceId, true);
    if (!result) return null;
    replayed = result.state;
  }
  const keys = ['nodeId', 'stats', 'flags', 'outfit', 'scarf', 'sister', 'father', 'endingId'] as const;
  // Earlier v3 builds committed arrest on entry to n02. Replaying that one
  // snapshot now restores the opening frame of the on-screen arrest; all other
  // fields and every action still have to match exactly. No invented fact survives.
  const legacyArrestFrame = input.nodeId === 'n02' && replayed.nodeId === 'n02' && input.history.length === 1 && input.father === 'missing' && replayed.father === 'free';
  const last = input.history.at(-1);
  const finish = last && NODES[last.nodeId]?.choices.find(choice => choice.id === last.choiceId)?.finish;
  const legacyEnding = Boolean(finish && input.endingId === previousEndingFor(replayed, finish));
  if (keys.some(key => !(key === 'father' && legacyArrestFrame) && !(key === 'endingId' && legacyEnding) && JSON.stringify(input[key]) !== JSON.stringify(replayed[key]))) return null;
  if (replayed.storyContentRevision === 6) return replayed;
  if (replayed.storyRevision === 5) {
    if (replayed.endingId) return replayed;
    // Old opening actions and workshop bookkeeping no longer mean the same
    // things. Do not replay them as consent to the new dialogue or preparation.
    let migrated = createInitialState('short');
    for (const step of replayed.history) {
      if (['n01', 'n10', 'n18'].includes(step.nodeId)) break;
      if (migrated.nodeId !== step.nodeId) break;
      const moved = chooseWithHistory(migrated, step.choiceId);
      if (!moved) break;
      migrated = moved.state;
    }
    return migrated;
  }
  if (replayed.endingId) return replayed;
  if (replayed.edition !== 'short') return replayed;
  // First authenticate the old snapshot above. Then keep its actual legal prefix
  // in the new graph; a removed late action returns to the real fork, never
  // fabricates a rescue, departure or adult life that the player did not choose.
  let migrated = createInitialState('short');
  for (const step of replayed.history) {
    // The old "stay" and "ask relatives" actions had different stakes. Their
    // reused IDs must not silently consent to a new separation or adult dream.
    if (['n01', 'n18'].includes(migrated.nodeId)) break;
    if (step.nodeId === 'n10' && step.choiceId === 'wage') break;
    if (migrated.nodeId !== step.nodeId || migrated.endingId) break;
    const moved = chooseWithHistory(migrated, step.choiceId);
    if (!moved) break;
    migrated = moved.state;
  }
  return migrated;
}
